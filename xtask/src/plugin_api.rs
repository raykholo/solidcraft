//! Generate the plugin reference from the shared WIT and MCP's engine descriptions.

use std::collections::BTreeMap;
use std::path::Path;
use std::process::Command;

use serde_json::Value;

const WIT: &str = "crates/craft-plugin/wit/plugin.wit";
const OUTPUT: &str = "docs/plugin-api";

pub fn run(root: &Path, args: &[&str]) -> Result<(), String> {
    let mut check = false;
    let mut cli = None;
    let mut args = args.iter().copied();
    while let Some(arg) = args.next() {
        match arg {
            "--check" => check = true,
            "--cli" => cli = Some(args.next().ok_or("plugin-api: --cli needs a path")?),
            _ => return Err(format!("plugin-api: unknown argument `{arg}`")),
        }
    }
    let mut command = match cli {
        Some(path) => Command::new(path),
        None => {
            let mut command = crate::cargo();
            command.args(["run", "--quiet", "--profile", "ci", "-p", "solidcraft-cli", "--"]);
            command
        }
    };
    let output = command.current_dir(root).args(["commands", "--schemas"]).output().map_err(|e| format!("plugin-api: solidcraft-cli: {e}"))?;
    if !output.status.success() {
        return Err(format!("plugin-api: solidcraft-cli commands --schemas failed:\n{}", String::from_utf8_lossy(&output.stderr)));
    }
    let commands: Value = serde_json::from_slice(&output.stdout).map_err(|e| format!("plugin-api: command schemas JSON: {e}"))?;
    let wit = std::fs::read_to_string(root.join(WIT)).map_err(|e| format!("{WIT}: {e}"))?;
    let files = reference(&wit, &commands)?;
    sync(&root.join(OUTPUT), &files, check)?;
    println!("plugin-api: {OUTPUT}/ {}", if check { "is current" } else { "generated" });
    Ok(())
}

/// Sort by command id so registry order cannot change the reference. Preserve the schemas
/// themselves: these descriptions come from the same engine.describe calls MCP serves.
pub(crate) fn reference(wit: &str, commands: &Value) -> Result<BTreeMap<String, String>, String> {
    let commands = commands.as_array().ok_or("plugin-api: command descriptions must be an array")?;
    let mut sorted = BTreeMap::new();
    for command in commands {
        let id = command.get("id").and_then(Value::as_str).ok_or("plugin-api: description has no command id")?;
        if sorted.insert(id, command).is_some() {
            return Err(format!("plugin-api: duplicate command `{id}`"));
        }
    }
    let mut json = serde_json::to_string_pretty(&sorted.into_values().collect::<Vec<_>>()).map_err(|e| format!("plugin-api: {e}"))?;
    json.push('\n');
    let readme = "# Plugin API reference\n\n\
        Generated by `cargo xtask plugin-api`. Do not edit these files by hand.\n\n\
        - [plugin.wit](plugin.wit): the component world, imports, exports and typed host errors,\n\
          copied from `crates/craft-plugin/wit/plugin.wit`. Generate Rust or TypeScript bindings from this file.\n\
        - [commands.json](commands.json): the engine command descriptions, input schemas and output schemas\n\
          returned by `engine.describe`, the same API served by MCP's `describe_command`.\n\n\
        A missing input or output schema means that command has not yet published that schema.\n\
        The host's command policy and the package's permissions determine which commands a plugin can run.\n\n\
        Run `cargo xtask plugin-api --check` to check freshness. The check regenerates the reference in memory\n\
        and fails if any generated file is missing, changed or unexpected.\n\n\
        See the [author guide](../plugin-guide.md) and [plugin skill](../../skills/solidcraft-plugins/SKILL.md).\n";
    Ok(BTreeMap::from([("README.md".into(), readme.into()), ("commands.json".into(), json), ("plugin.wit".into(), wit.replace("\r\n", "\n"))]))
}

/// Check every generated file, including unexpected files, so deleted API outputs cannot linger.
pub(crate) fn sync(dir: &Path, files: &BTreeMap<String, String>, check: bool) -> Result<(), String> {
    let mut stale = Vec::new();
    if dir.exists() {
        for entry in std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))? {
            let entry = entry.map_err(|e| format!("{}: {e}", dir.display()))?;
            let name = entry.file_name().to_string_lossy().into_owned();
            if !files.contains_key(&name) {
                stale.push(format!("unexpected {name}"));
            }
        }
    }
    for (name, expected) in files {
        if check {
            let actual = std::fs::read_to_string(dir.join(name));
            if !actual.is_ok_and(|actual| actual.replace("\r\n", "\n") == *expected) {
                stale.push(name.clone());
            }
        } else {
            std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
            std::fs::write(dir.join(name), expected).map_err(|e| format!("{}: {e}", dir.join(name).display()))?;
        }
    }
    if stale.is_empty() {
        Ok(())
    } else {
        Err(format!("plugin-api: stale reference ({}); run `cargo xtask plugin-api` and remove unexpected files", stale.join(", ")))
    }
}
